const week = (
  pattern: Record<string, ("manha" | "tarde" | "noite")[]>,
): DayAvailability[] => {
  const days: { day: string; short: string }[] = [
    { day: "Segunda", short: "Seg" },
    { day: "Terça", short: "Ter" },
    { day: "Quarta", short: "Qua" },
    { day: "Quinta", short: "Qui" },
    { day: "Sexta", short: "Sex" },
    { day: "Sábado", short: "Sáb" },
    { day: "Domingo", short: "Dom" },
  ];
  return days.map(({ day, short }) => ({
    day,
    shortDay: short,
    parts: pattern[short] ?? [],
  }));
};

